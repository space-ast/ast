/// @brief 高度表格行数
static const int N_ALT = 59;

/// @brief F107 等级数
static const int N_F107 = 10;

/// @brief 周日 bulge 滞后角 [rad]
/// @details 大气密度在太阳过顶后约 2 小时（30°）达到峰值。
///          因此 bulge 顶点在太阳方向以东（右经增加方向）30° 处。
static const double LAG_ANGLE = 30_deg;  // 30 * π / 180

/// @brief cos(30°) — 预计算以加速
static const double COS_LAG = cos(LAG_ANGLE);    // cos(30°)

/// @brief sin(30°) — 预计算以加速
static const double SIN_LAG = 0.5;                    // sin(30°)

/// @brief 余弦指数 n
/// @details Montenbruck & Gill《Satellite Orbits》推荐：
///          - n=2 用于低倾角轨道（赤道附近）
///          - n=6 用于极地轨道
///          - n=4 为默认值，适用于大多数情况
// static const double COSINE_EXPONENT = 4.0;

/// @brief cos(ψ/2) 最小值，低于此值时 cosPow 视为 0
/// @details 避免对极小值做 pow 运算导致下溢
static const double MIN_COS_HALF = 1.0e-12;

// =========================================================================
//  aHarrisPriester — Harris-Priester 大气密度模型
// =========================================================================
//
//  基于 Harris-Priester 模型计算大气密度。
//  模型考虑了周日 bulge 效应（大气密度在太阳方向后方约 30° 处达到峰值），
//  并通过 F10.7 太阳辐射通量参数考虑太阳活动对大气密度的影响。
//
//  参考文献：Montenbruck O., Gill E., "Satellite Orbits", Springer 2005, §3.5
//
//  ---- 参考实现对比 ----
//
//  参考了三个独立实现：
//    - Orekit (Java): org.orekit.models.earth.atmosphere.HarrisPriester
//    - GPSTk (C++):  gpstk::HarrisPriesterDrag
//    - 42 Project (C): val_atm_hp (Eric Stoneking)
//
//  三个参考实现的核心算法一致：
//    1. 太阳方向绕 Z 轴旋转 30° 得到周日 bulge 顶点方向
//    2. 在 min/max 密度之间做 cos^n(ψ/2) 插值
//    3. 高度方向使用指数插值
//
//  差异点：
//    - Orekit 使用单一密度表（平均太阳活动），不做 F107 插值
//    - GPSTk 和 42 使用 10 级 F107 表格，做 F107 线性插值
//    - 余弦指数：Orekit n=4，GPSTk 从轨道倾角计算 2~6，42 固定 3
//
//  本实现的设计选择：
//    - F107 插值：采用 42 的高效双线性策略（只在 2 个高度点做 F107 插值，共 4 次 lerp）
//    - 密度表：GPSTk 的 10 级 F107 表格（110–2000 km），数据去冗余（altitude 只存一份）
//    - 余弦指数作为函数参数，范围 [2-6]

double aHarrisPriester(
    const Vector3d& pos,
    const Vector3d& sunpos,
    double altitude,
    double f107,
    int n
)
{
    // ---- 第 1 步：高度单位转换与边界检查 ----
    // 输入 altitude 单位为 [m]，表格单位为 [km]
    double alt_km = altitude / 1000.0;

    // 高于表格最大高度 (2000 km)，大气密度视为 0
    if (alt_km >= ALTITUDE_GRID[N_ALT - 1])
    {
        return 0.0;
    }

    // 低于表格最小高度 (110 km)，钳位到最低高度
    // 注意：Harris-Priester 模型在 100 km 以下不准确，建议使用 USSA1976
    if (alt_km < ALTITUDE_GRID[0])
    {
        alt_km = ALTITUDE_GRID[0];
    }

    // ---- 第 2 步：查找 F107 的 bracket（相邻两个 F107 等级） ----
    // 在 F107_LEVELS 中找到 f107 的下界索引 (ilo) 和上界索引 (ihi)
    int ilo = 0;
    for (int i = 0; i < N_F107 - 1 && ilo == 0; ++i)
    {
        if (f107 < F107_LEVELS[i + 1])
        {
            ilo = i;
        }
    }
    // 若 f107 大于等于最大 F107 等级，使用最后两个等级
    if (ilo == 0 && f107 >= F107_LEVELS[N_F107 - 1])
    {
        ilo = N_F107 - 2;
    }
    int ihi = ilo + 1;

    // F107 线性插值因子，钳位到 [0, 1]（不做外推）
    double ifactor = (f107 - F107_LEVELS[ilo]) / (F107_LEVELS[ihi] - F107_LEVELS[ilo]);
    if (ifactor < 0.0) ifactor = 0.0;
    if (ifactor > 1.0) ifactor = 1.0;

    // ---- 第 3 步：查找高度的 bracket（相邻两个高度网格点） ----
    int jlo = 0;
    for (int j = 0; j < N_ALT - 1 && jlo == 0; ++j)
    {
        if (alt_km < ALTITUDE_GRID[j + 1])
        {
            jlo = j;
        }
    }
    // 若 altitude 超出最大高度，使用最后两个网格点（正常情况下不会到这里，
    // 因为第 1 步已对 >2000 km 提前返回，这里作为保护）
    if (jlo == 0 && alt_km >= ALTITUDE_GRID[N_ALT - 1])
    {
        jlo = N_ALT - 2;
    }
    int jhi = jlo + 1;

    // 高度线性插值因子（用于后续指数插值）
    double jfactor = (alt_km - ALTITUDE_GRID[jlo]) / (ALTITUDE_GRID[jhi] - ALTITUDE_GRID[jlo]);

    // ---- 第 4 步：在 jlo 和 jhi 两个高度上做 F107 线性插值 ----
    // 采用 42 项目的高效策略：只在 2 个高度点做 F107 插值（共 4 次 lerp），
    // 而非像 GPSTk 那样先生成完整的 59 行工作表格（118 次 lerp）。
    // 两种方式数学等价，但本方案效率更高。

    // 在下界高度 jlo 处插值
    double min_jlo = MIN_DENSITY[ilo][jlo] + ifactor * (MIN_DENSITY[ihi][jlo] - MIN_DENSITY[ilo][jlo]);
    double max_jlo = MAX_DENSITY[ilo][jlo] + ifactor * (MAX_DENSITY[ihi][jlo] - MAX_DENSITY[ilo][jlo]);

    // 在上界高度 jhi 处插值
    double min_jhi = MIN_DENSITY[ilo][jhi] + ifactor * (MIN_DENSITY[ihi][jhi] - MIN_DENSITY[ilo][jhi]);
    double max_jhi = MAX_DENSITY[ilo][jhi] + ifactor * (MAX_DENSITY[ihi][jhi] - MAX_DENSITY[ilo][jhi]);

    // ---- 第 5 步：高度方向的指数插值 ----
    // 大气密度随高度近似指数衰减：
    //   ρ(h) = ρ(h₀) × (ρ(h₁) / ρ(h₀)) ^ ((h - h₀) / (h₁ - h₀))
    // 即：ρ = ρ_jlo × (ρ_jhi / ρ_jlo)^jfactor
    double min_density = min_jlo * std::pow(min_jhi / min_jlo, jfactor);
    double max_density = max_jlo * std::pow(max_jhi / max_jlo, jfactor);

    // ---- 第 6 步：计算周日 bulge 顶点方向 ----
    // 大气密度由于太阳加热存在周日变化：
    // - 密度在"bulge 顶点"处最大（ρ_max）
    // - 密度在 bulge 的反方向（antapode）处最小（ρ_min）
    // - bulge 顶点滞后于太阳方向约 30°（约 2 小时），因为大气加热需要时间
    //
    // bulge 顶点方向 = 太阳方向绕 Z 轴（地球自转轴）正向旋转 30°
    // 旋转矩阵: [cos(30°)  -sin(30°)   0]
    //           [sin(30°)   cos(30°)   0]
    //           [   0          0       1]

    double sun_norm = sunpos.norm();
    double sun_ux = sunpos.x() / sun_norm;
    double sun_uy = sunpos.y() / sun_norm;
    double sun_uz = sunpos.z() / sun_norm;

    // 绕 Z 轴旋转 +30°
    double bulge_ux = sun_ux * COS_LAG - sun_uy * SIN_LAG;
    double bulge_uy = sun_ux * SIN_LAG + sun_uy * COS_LAG;
    double bulge_uz = sun_uz;

    // ---- 第 7 步：计算航天器方向与 bulge 顶点的夹角 ψ ----
    double pos_norm = pos.norm();
    double pos_ux = pos.x() / pos_norm;
    double pos_uy = pos.y() / pos_norm;
    double pos_uz = pos.z() / pos_norm;

    // cos(ψ) = 航天器单位方向 · bulge 单位方向
    double cos_psi = pos_ux * bulge_ux + pos_uy * bulge_uy + pos_uz * bulge_uz;

    // ---- 第 8 步：计算 cosⁿ(ψ/2) ----
    // 利用半角公式：cos²(ψ/2) = (1 + cos(ψ)) / 2
    double cos2_half = (1.0 + cos_psi) / 2.0;

    // cos(ψ/2) = √(cos²(ψ/2))
    double cos_half = std::sqrt(cos2_half);

    // cosⁿ(ψ/2)，其中 n 是输入的余弦指数
    // 计算方式：cos²(ψ/2) × cos^(n-2)(ψ/2)，与 Orekit 一致
    // 当 cos(ψ/2) 极小时（航天器在 bulge 反面），cosPow ≈ 0，密度取最小值
    double cos_pow;
    if (cos_half > MIN_COS_HALF)
    {
        cos_pow = cos2_half * std::pow(cos_half, n - 2.0);
    }
    else
    {
        cos_pow = 0.0;
    }

    // ---- 第 9 步：最终密度计算 ----
    // ρ = ρ_min + (ρ_max - ρ_min) × cosⁿ(ψ/2)
    //
    // 物理含义：
    // - 航天器在 bulge 顶点方向：cosⁿ(ψ/2) ≈ 1 → ρ ≈ ρ_max（密度最大）
    // - 航天器在 bulge 反面：cosⁿ(ψ/2) ≈ 0 → ρ ≈ ρ_min（密度最小）
    // - 航天器在中间位置：ρ 在 ρ_min 和 ρ_max 之间平滑过渡
    double density = min_density + (max_density - min_density) * cos_pow;

    // 表格密度单位为 10⁻⁹ kg/m³，乘以 1e-9 转换为 kg/m³
    return density * 1.0e-9;
}

